function encodeKey(safeStorage, key) {
  if (!key) return ''
  try {
    if (safeStorage && safeStorage.isEncryptionAvailable()) return 'enc:' + safeStorage.encryptString(key).toString('base64')
  } catch (e) {}
  return 'raw:' + Buffer.from(key, 'utf8').toString('base64')
}

function decodeKey(safeStorage, stored) {
  if (!stored) return ''
  try {
    if (stored.startsWith('enc:')) return safeStorage.decryptString(Buffer.from(stored.slice(4), 'base64'))
    if (stored.startsWith('raw:')) return Buffer.from(stored.slice(4), 'base64').toString('utf8')
  } catch (e) {}
  return ''
}

function clip(text, limit) {
  const t = String(text || '')
  return t.length > limit ? t.slice(t.length - limit) : t
}

function parseJson(text) {
  try {
    return JSON.parse(text)
  } catch (e) {}
  const a = text.indexOf('{')
  const b = text.lastIndexOf('}')
  if (a >= 0 && b > a) {
    try {
      return JSON.parse(text.slice(a, b + 1))
    } catch (e) {}
  }
  return null
}

function friendlyError(prov, status, code, raw) {
  const who = prov.short || 'The AI service'
  if (code === 'insufficient_quota' || status === 402 || /credit balance is too low/i.test(raw) || (status === 429 && /quota|billing|credit/i.test(raw))) {
    return 'Your ' + who + ' key is valid, but the account has no API credits left. Add credits in your ' + who + ' account billing. A chat subscription does not include API credits.'
  }
  if (status === 401 || status === 403) return who + ' did not accept this key. Check that it was copied fully in App Settings.'
  if (status === 429) return who + ' is limiting requests right now. Wait a moment and try again.'
  if (status === 404 || code === 'model_not_found') return 'That model is not available on your ' + who + ' account. Change the model in App Settings.'
  return raw
}

function mergeTurns(list) {
  const out = []
  list.forEach(m => {
    const last = out[out.length - 1]
    if (last && last.role === m.role) last.content += '\n\n' + m.content
    else out.push({ role: m.role, content: m.content })
  })
  while (out.length && out[0].role !== 'user') out.shift()
  return out
}

async function complete(prov, key, body, signal) {
  let headers
  let payload
  if (prov.kind === 'anthropic') {
    const sys = body.messages.filter(m => m.role === 'system').map(m => m.content).join('\n\n')
    headers = { 'Content-Type': 'application/json', 'x-api-key': key, 'anthropic-version': '2023-06-01' }
    payload = { model: body.model, max_tokens: 4096, messages: mergeTurns(body.messages.filter(m => m.role !== 'system')) }
    if (sys) payload.system = sys
  } else {
    headers = { 'Content-Type': 'application/json', Authorization: 'Bearer ' + key }
    payload = body
  }
  let res
  try {
    res = await fetch(prov.url, { method: 'POST', headers, body: JSON.stringify(payload), signal: signal || AbortSignal.timeout(120000) })
  } catch (e) {
    throw new Error('Could not reach ' + (prov.short || 'the AI service') + '. Check your internet connection and the API address.')
  }
  const raw0 = await res.json().catch(() => null)
  const data = Array.isArray(raw0) ? raw0[0] : raw0
  if (!res.ok) {
    const info = (data && data.error) || {}
    const raw = info.message || 'request failed (HTTP ' + res.status + ')'
    const err = new Error(friendlyError(prov, res.status, info.code || info.type, raw))
    err.status = res.status
    err.raw = raw
    throw err
  }
  if (prov.kind === 'anthropic') {
    return ((data && data.content) || []).filter(b => b && b.type === 'text').map(b => b.text).join('')
  }
  const msg = data && data.choices && data.choices[0] && data.choices[0].message
  return String((msg && msg.content) || '')
}

function walkShaders(paths) {
  const out = []
  const seen = new Set()
  const visit = (p, depth) => {
    if (out.length >= 400 || seen.has(p)) return
    seen.add(p)
    let st
    try {
      st = fs.statSync(p)
    } catch (e) {
      return
    }
    if (st.isDirectory()) {
      if (depth > 6) return
      let names = []
      try {
        names = fs.readdirSync(p)
      } catch (e) {}
      names.forEach(n => visit(path.join(p, n), depth + 1))
    } else if (/\.shader$/i.test(p)) {
      out.push(p)
    }
  }
  paths.forEach(p => visit(p, 0))
  return out
}

function parseCheck(output) {
  const lines = String(output || '').replace(/\r/g, '').split('\n')
  const files = new Map()
  const get = name => {
    if (!files.has(name)) files.set(name, { name, code: [], unity: [], codeLeft: null, unityErrors: 0 })
    return files.get(name)
  }
  let cur = null
  let mode = ''
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i]
    if (/^={20,}$/.test(l) && i + 2 < lines.length && /^={20,}$/.test(lines[i + 2]) && lines[i + 1].trim()) {
      cur = get(lines[i + 1].trim())
      cur.code = []
      mode = 'code'
      i += 2
      continue
    }
    if (!l.startsWith(' ')) {
      const m = l.match(/^(.+?): Unity (?:still reports \d+ error|compiles)/)
      if (m) {
        cur = get(m[1].trim())
        cur.unity = []
        mode = 'unity'
        continue
      }
    }
    if (/^summary:/.test(l)) {
      mode = 'summary'
      cur = null
      continue
    }
    if (mode === 'summary') {
      const m = l.match(/^\s+(.+?): (\d+) code error\(s\) left(.*)$/)
      if (m) {
        const f = get(m[1].trim())
        f.codeLeft = Number(m[2])
        const u = m[3].match(/Unity: (?:compiles|(\d+) error)/)
        f.unityErrors = u && u[1] ? Number(u[1]) : 0
      }
      continue
    }
    if (!cur) continue
    if (mode === 'code' && /^\s+still open: \d+/.test(l)) {
      cur.code = []
      continue
    }
    if (/^\s+ERROR\b/.test(l)) {
      ;(mode === 'unity' ? cur.unity : cur.code).push(l.trim())
      continue
    }
    if (mode === 'unity' && cur.unity.length && /^\s{8}(>|hint:)/.test(l)) {
      cur.unity[cur.unity.length - 1] += '\n' + l.trim()
    }
  }
  return files
}

function errorTotal(entry) {
  if (!entry || entry.codeLeft === null) return Infinity
  return entry.codeLeft + entry.unityErrors
}

function errorText(entry) {
  const parts = []
  if (entry.code.length) parts.push('Checker errors:\n' + entry.code.slice(0, 40).join('\n'))
  if (entry.unity.length) parts.push('Unity compile errors:\n' + entry.unity.slice(0, 40).join('\n'))
  return parts.join('\n\n')
}

function shaderExcerpt(text, errors) {
  if (text.length <= MAX_FILE_CHARS) return text
  const lines = text.split('\n')
  const marks = new Set([0])
  const re = /line (\d+)/g
  let m
  while ((m = re.exec(errors))) marks.add(Math.max(0, Number(m[1]) - 1))
  const ranges = []
  Array.from(marks).sort((a, b) => a - b).forEach(n => {
    const a = Math.max(0, n - WINDOW_LINES)
    const b = Math.min(lines.length - 1, n + WINDOW_LINES)
    const last = ranges[ranges.length - 1]
    if (last && a <= last[1] + 1) last[1] = Math.max(last[1], b)
    else ranges.push([a, b])
  })
  const out = []
  let prev = -1
  ranges.forEach(([a, b]) => {
    if (a > prev + 1) out.push('[... lines ' + (prev + 2) + '-' + a + ' omitted, do not use this marker in any find ...]')
    out.push(lines.slice(a, b + 1).join('\n'))
    prev = b
  })
  if (prev < lines.length - 1) out.push('[... lines ' + (prev + 2) + '-' + lines.length + ' omitted, do not use this marker in any find ...]')
  return out.join('\n')
}

function balance(t) {
  return (t.match(/{/g) || []).length - (t.match(/}/g) || []).length
}

function applyEdits(text, edits) {
  let next = text
  let applied = 0
  let skipped = 0
  edits.slice(0, MAX_EDITS).forEach(e => {
    if (!e || typeof e.find !== 'string' || typeof e.replace !== 'string' || !e.find || e.find === e.replace) {
      skipped++
      return
    }
    const first = next.indexOf(e.find)
    if (first < 0 || next.indexOf(e.find, first + 1) >= 0) {
      skipped++
      return
    }
    next = next.slice(0, first) + e.replace + next.slice(first + e.find.length)
    applied++
  })
  if (applied && balance(text) === 0 && balance(next) !== 0) return { text, applied: 0, skipped: skipped + applied, unbalanced: true }
  return { text: next, applied, skipped }
}

function createAi(deps) {
  const { safeStorage, getSettings, saveSettings, runEngine, send, isStopped } = deps

  const log = text => send('engine:log', text + '\n')

  function keys() {
    const s = getSettings()
    const k = Object.assign({}, s.aiKeys || {})
    if (s.aiKeyStored && !k.openai) k.openai = s.aiKeyStored
    return k
  }
  const activeId = () => (PROVIDERS[getSettings().aiProvider] ? getSettings().aiProvider : 'openai')
  function provider() {
    const id = activeId()
    const p = Object.assign({}, PROVIDERS[id])
    if (id === 'custom') p.url = String(getSettings().aiCustomUrl || '').trim()
    return p
  }
  const getKey = () => decodeKey(safeStorage, keys()[activeId()])
  function models() {
    const s = getSettings()
    const id = activeId()
    const m = (s.aiModels || {})[id] || {}
    const p = PROVIDERS[id]
    return {
      chat: m.chat || (id === 'openai' && s.aiModel) || p.chat,
      fix: m.fix || (id === 'openai' && s.aiFixModel) || p.fix
    }
  }
  function setupProblem() {
    if (!getKey()) return 'Add your ' + PROVIDERS[activeId()].short + ' API key in App Settings first.'
    const p = provider()
    if (!p.url) return 'Add the API address for your AI service in App Settings first.'
    const m = models()
    if (!m.chat) return 'Add a model name for your AI service in App Settings first.'
    return ''
  }

  function status() {
    const k = keys()
    const m = models()
    return {
      hasKey: !!getKey(),
      provider: activeId(),
      providers: Object.values(PROVIDERS).map(p => ({ id: p.id, name: p.name, short: p.short, chat: p.chat, fix: p.fix, hint: p.hint, site: p.site, hasKey: !!decodeKey(safeStorage, k[p.id]) })),
      model: m.chat,
      fixModel: m.fix,
      customUrl: String(getSettings().aiCustomUrl || '')
    }
  }

  function setKey(key, id) {
    const pid = PROVIDERS[id] ? id : activeId()
    const next = Object.assign({}, keys())
    next[pid] = encodeKey(safeStorage, String(key || '').trim())
    saveSettings({ aiKeys: next, aiKeyStored: '' })
    return status()
  }

  async function chat(payload) {
    const problem = setupProblem()
    if (problem) return { ok: false, error: problem }
    const key = getKey()
    const p = payload || {}
    const targets = Array.isArray(p.targets) ? p.targets : []
    const history = (Array.isArray(p.messages) ? p.messages : [])
      .filter(m => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string')
      .slice(-HISTORY_LIMIT)
    if (!history.length) return { ok: false, error: 'empty message' }
    const ctx = []
    ctx.push('Current tab: ' + String(p.tab || 'unknown'))
    if (p.selection) ctx.push('Text the user selected:\n' + clip(p.selection, CONTEXT_LIMIT))
    if (p.region) ctx.push('Screen area the user picked:\n' + clip(p.region, CONTEXT_LIMIT))
    if (p.log) ctx.push('Recent output log:\n' + clip(p.log, CONTEXT_LIMIT))
    if (targets.length) ctx.push('Pointable items (id: description):\n' + targets.map(t => t.id + ': ' + t.label + (t.desc ? ' - ' + t.desc : '')).join('\n'))
    const messages = [{ role: 'system', content: APP_GUIDE + '\n\n' + ctx.join('\n\n') }].concat(history)
    try {
      const text = await complete(provider(), key, { model: models().chat, messages })
      return { ok: true, text: text.trim() }
    } catch (e) {
      return { ok: false, error: e.message }
    }
  }

  async function requestEdits(key, model, errors, text) {
    const user = 'Errors to fix:\n' + errors + '\n\nShader text:\n' + shaderExcerpt(text, errors)
    const prov = provider()
    const body = {
      model,
      messages: [{ role: 'system', content: FIX_SYSTEM }, { role: 'user', content: user }]
    }
    if (prov.kind !== 'anthropic') body.response_format = { type: 'json_object' }
    let raw
    try {
      raw = await complete(prov, key, body)
    } catch (e) {
      if (e.status === 400 && /response_format/i.test(e.raw || e.message)) {
        delete body.response_format
        raw = await complete(prov, key, body)
      } else {
        throw e
      }
    }
    const data = parseJson(raw)
    if (!data || !Array.isArray(data.edits)) return { edits: [], explanation: 'the reply could not be read' }
    return { edits: data.edits, explanation: String(data.explanation || '') }
  }

  async function recheck(file, useUnity) {
    const args = ['--check-shader', file, '--no-fix']
    if (!useUnity) args.push('--no-unity')
    const res = await runEngine(args)
    const entry = parseCheck(res.output).get(path.basename(file))
    return entry
  }

  async function fixOne(key, model, file, entry, useUnity) {
    const name = path.basename(file)
    let current = entry
    let round = 0
    while (round < FIX_ROUNDS && !isStopped()) {
      round++
      const before = errorTotal(current)
      if (!before) return
      const raw = fs.readFileSync(file, 'utf8')
      const crlf = raw.includes('\r\n')
      const text = raw.replace(/\r\n/g, '\n')
      log('AI: asking for a fix for ' + name + (round > 1 ? ' (round ' + round + ')' : '') + '...')
      let result
      try {
        result = await requestEdits(key, model, errorText(current), text)
      } catch (e) {
        log('AI: request failed for ' + name + ': ' + e.message)
        return
      }
      if (!result.edits.length) {
        log('AI: no fix proposed for ' + name + (result.explanation ? ' (' + result.explanation + ')' : ''))
        return
      }
      const applied = applyEdits(text, result.edits)
      if (!applied.applied) {
        log('AI: its edits did not match the file, nothing changed for ' + name)
        return
      }
      fs.writeFileSync(file, crlf ? applied.text.replace(/\n/g, '\r\n') : applied.text, 'utf8')
      log('AI: applied ' + applied.applied + ' edit(s) to ' + name + (applied.skipped ? ', skipped ' + applied.skipped : '') + (result.explanation ? ': ' + result.explanation : ''))
      const after = await recheck(file, useUnity)
      if (errorTotal(after) >= before) {
        fs.writeFileSync(file, raw, 'utf8')
        log('AI: ' + name + ' did not get better (' + (after ? errorTotal(after) : 'unknown') + ' vs ' + before + ' errors), put the previous version back.')
        return
      }
      log('AI: ' + name + ' went from ' + before + ' to ' + errorTotal(after) + ' error(s).')
      current = after
    }
  }

  async function fixShaders(opts) {
    const problem = setupProblem()
    if (problem) {
      log('AI fix skipped: ' + problem)
      return
    }
    const key = getKey()
    const files = walkShaders(opts.paths || [])
    const found = parseCheck(opts.output)
    const model = models().fix || models().chat
    const todo = files.filter(f => errorTotal(found.get(path.basename(f))) > 0 && errorTotal(found.get(path.basename(f))) !== Infinity)
    if (!todo.length) {
      log('AI fix: no remaining errors to fix.')
      return
    }
    log('AI fix: ' + todo.length + ' shader(s) still have errors.')
    for (const f of todo) {
      if (isStopped()) break
      await fixOne(key, model, f, found.get(path.basename(f)), opts.useUnity)
    }
    log('AI fix finished')
  }

  return { status, setKey, chat, fixShaders }
}

